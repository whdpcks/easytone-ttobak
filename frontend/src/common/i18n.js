export const DICT = { ko, en, zh, ja, vi, th, id, fil, km, my, hi, ne };

export function translate(lang, key, vars) {
  const raw = DICT[lang]?.[key] ?? DICT.en[key] ?? DICT.ko[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export function useT() {
  const { lang } = useSettings();
  return useCallback((key, vars) => translate(lang, key, vars), [lang]);
}

/** 서버 오류(한국어 문장)를 지금 언어의 문장으로 바꿉니다. */
export function errorText(t, e) {
  if (!e) return '';
  if (e.status === 0) return t('err.network');
  const m = String(e.message || '');
  const rules = [
    ['맞지 않아요', 'err.codeWrong'], ['시간이 지났어요', 'err.codeExpired'], ['먼저 받아', 'err.codeFirst'],
    ['여러 번 틀렸어요', 'err.locked'], ['가입하지 않은', 'err.notRegistered'], ['이미 가입한', 'err.registered'],
    ['전화번호를 다시', 'err.phone'], ['5명까지', 'err.familyMax'],
  ];
  for (const [needle, key] of rules) if (m.includes(needle)) return t(key);
  const wait = m.match(/(\d+)초 뒤에/);
  if (wait) return t('err.tooSoon', { s: wait[1] });
  return t('err.generic');
}
